  `polygon(${points.map(([x, y]) => `${x}% ${y}%`).join(', ')})`;

export function stickerTilt(petId: string): number {
  let h = 0;
  for (let i = 0; i < petId.length; i++) h = (h * 31 + petId.charCodeAt(i)) | 0;
  return ((Math.abs(h) % 121) - 60) / 10;
}
